/**
 * 공개 게이트 — 채널×도시에 확정 핀이 이 수 이상이면 공개한다.
 * 홈·허브·조각 페이지·사이트맵이 같은 상수를 쓴다.
 *
 * 2026-08-10 운영자 결정: 1개면 충분. 예전 8핀 완성형 조각 원칙은 폐기.
 * **2026-08-21 상향: 2개.** 1핀 조각이 "그 유튜버 그 도시 맛집"에 답을 못 한다.
 *
 * 상향 근거 — 그날 실측한 조각 분포:
 *
 *   임계 2  조각  67개(35%) 가림 · 장소   67곳( 4%) 빠짐   ← 채택
 *   임계 3  조각  98개(52%) 가림 · 장소  129곳( 8%) 빠짐
 *   임계 5  조각 126개(67%) 가림 · 장소  222곳(13%) 빠짐
 *
 * 2에서 비용 대비 효과가 가장 좋다. 조각 3분의 1을 접는데 장소는 4%만 빠진다 —
 * 그 67곳은 전부 "1곳짜리 조각"이라 원래 페이지 하나에 가게 하나였다.
 * 저품질 페이지 양산은 AdSense 독립적 가치 요건에도 불리하다(`0001_init.sql:116`).
 *
 * 미달 조각은 404 가 아니다 — `PendingPiece`(준비 중) 화면이 나가고 `noindex` 가
 * 붙으며 사이트맵에서 빠진다. 장소 자체는 지도·도시·종류 페이지에 그대로 남는다.
 *
 * 환경변수로 덮어쓸 수 있다:
 *   NEXT_PUBLIC_MIN_CONFIRMED_PINS=0 npm run dev   ← 0이면 빈 조각까지 통과(비권장)
 *
 * ⚠️ NEXT_PUBLIC_ 값은 정적 리터럴로 접근해야 번들에 인라인된다 (`env.ts` 상단 주석 참조).
 */
const OVERRIDE = Number.parseInt(process.env["NEXT_PUBLIC_MIN_CONFIRMED_PINS"] ?? "", 10);

/** 제품 기준값 — 확정 핀 2개 이상이면 공개. */
export const PRODUCTION_MIN_CONFIRMED_PINS = 2;

export const MIN_CONFIRMED_PINS =
  Number.isInteger(OVERRIDE) && OVERRIDE >= 0 ? OVERRIDE : PRODUCTION_MIN_CONFIRMED_PINS;

/**
 * **도시**가 목록·지도에 뜨는 최소 확정 핀 수. 위 조각 게이트와 **분리해 둔다.**
 *
 * ⚠️ 한 상수로 묶으면 안 된다. `cities.ts` 의 도시 색인이 게이트를 통과 못 하면
 *    그 도시가 `loadHomeMap` 의 `publishedCities` 에서 빠지고(cities.ts:495),
 *    `loadPlaceIndex` 가 그 위에 얹혀 있어 **장소 상세가 통째로 404 가 된다.**
 *    2026-08-21 에 조각 게이트를 2 로 올렸더니 장소 1곳뿐인 도시 42개의
 *    상세 페이지 42개가 404 로 떨어졌다(실측). 이미 색인된 URL 이라 SEO 손해다.
 *
 * 조각(채널×도시)이 얇은 것과 도시가 얇은 것은 다른 문제다. 1곳짜리 도시라도
 * 그 장소 페이지는 멀쩡한 답이므로 살려 둔다 — 접는 건 조각 페이지뿐이다.
 */
export const MIN_CITY_PINS = 1;
